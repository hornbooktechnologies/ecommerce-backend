CREATE TABLE seller_ratings (
  id BINARY(16) NOT NULL PRIMARY KEY,
  tenant_id BINARY(16) NOT NULL,
  store_id BINARY(16) NOT NULL,
  merchant_id BINARY(16) NOT NULL,
  customer_id BINARY(16) NOT NULL,
  customer_order_id BINARY(16) NOT NULL,
  seller_order_id BINARY(16) NOT NULL,
  rating TINYINT UNSIGNED NOT NULL,
  review_text TEXT NOT NULL,
  customer_first_name VARCHAR(80) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
  moderation_note VARCHAR(1000) NULL,
  moderated_by BINARY(16) NULL,
  moderated_at DATETIME(6) NULL,
  version INT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_seller_rating_order (seller_order_id),
  KEY ix_seller_rating_public (tenant_id,store_id,merchant_id,status,created_at),
  KEY ix_seller_rating_queue (tenant_id,status,created_at),
  FOREIGN KEY (tenant_id) REFERENCES tenants(id),
  FOREIGN KEY (store_id) REFERENCES stores(id),
  FOREIGN KEY (merchant_id) REFERENCES merchants(id),
  FOREIGN KEY (customer_id) REFERENCES customers(id),
  FOREIGN KEY (customer_order_id) REFERENCES customer_orders(id),
  FOREIGN KEY (seller_order_id) REFERENCES seller_orders(id),
  FOREIGN KEY (moderated_by) REFERENCES users(id),
  CHECK (rating BETWEEN 1 AND 5),
  CHECK (status IN ('PENDING','PUBLISHED','REJECTED','HIDDEN'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
